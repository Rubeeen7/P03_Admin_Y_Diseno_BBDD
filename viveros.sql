BEGIN;
DROP TABLE IF EXISTS destino, desempena, stock, pedido, cliente, puesto, empleado, producto, zona, vivero CASCADE;
CREATE TABLE vivero (
 id_vivero INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 latitud NUMERIC(9,6) NOT NULL CHECK(latitud BETWEEN -90 AND 90),
 longitud NUMERIC(9,6) NOT NULL CHECK(longitud BETWEEN -180 AND 180)
);
CREATE TABLE zona (
 id_zona INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_vivero INTEGER NOT NULL REFERENCES vivero(id_vivero) ON UPDATE CASCADE ON DELETE RESTRICT,
 nombre VARCHAR(100) NOT NULL,
 latitud NUMERIC(9,6) NOT NULL CHECK(latitud BETWEEN -90 AND 90),
 longitud NUMERIC(9,6) NOT NULL CHECK(longitud BETWEEN -180 AND 180),
 UNIQUE(id_vivero,nombre)
);
CREATE TABLE producto (
 id_producto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(100) NOT NULL
);
CREATE TABLE empleado (
 dni VARCHAR(9) PRIMARY KEY CHECK (dni ~ '^[0-9]{8}[A-Z]$'),
 nombre VARCHAR(80) NOT NULL,
 apellidos VARCHAR(120) NOT NULL
);
CREATE TABLE puesto (
 id_puesto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(100) NOT NULL UNIQUE
);
CREATE TABLE cliente (
 id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(120) NOT NULL,
 fecha_ingreso_plus DATE,
 bonificacion NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK(bonificacion BETWEEN 0 AND 100),
 CHECK(fecha_ingreso_plus IS NULL OR fecha_ingreso_plus <= CURRENT_DATE)
);
CREATE TABLE stock (
 id_zona INTEGER NOT NULL REFERENCES zona(id_zona) ON UPDATE CASCADE ON DELETE CASCADE,
 id_producto INTEGER NOT NULL REFERENCES producto(id_producto) ON UPDATE CASCADE ON DELETE RESTRICT,
 cantidad_disponible INTEGER NOT NULL DEFAULT 0 CHECK(cantidad_disponible >= 0),
 PRIMARY KEY(id_zona,id_producto)
);
CREATE TABLE desempena (
 id_desempena INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 dni_empleado VARCHAR(9) NOT NULL REFERENCES empleado(dni) ON UPDATE CASCADE ON DELETE CASCADE,
 id_puesto INTEGER NOT NULL REFERENCES puesto(id_puesto) ON UPDATE CASCADE ON DELETE RESTRICT,
 fecha_inicio DATE NOT NULL,
 fecha_fin DATE,
 CHECK(fecha_fin IS NULL OR fecha_fin >= fecha_inicio),
 UNIQUE(dni_empleado,id_puesto,fecha_inicio)
);
CREATE TABLE destino (
 id_destino INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 dni_empleado VARCHAR(9) NOT NULL REFERENCES empleado(dni) ON UPDATE CASCADE ON DELETE CASCADE,
 id_zona INTEGER NOT NULL REFERENCES zona(id_zona) ON UPDATE CASCADE ON DELETE CASCADE,
 fecha_inicio DATE NOT NULL,
 fecha_fin DATE,
 productividad NUMERIC(7,2) CHECK(productividad IS NULL OR productividad >= 0),
 CHECK(fecha_fin IS NULL OR fecha_fin >= fecha_inicio),
 UNIQUE(dni_empleado,id_zona,fecha_inicio)
);
CREATE TABLE pedido (
 id_pedido INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_cliente INTEGER NOT NULL REFERENCES cliente(id_cliente) ON UPDATE CASCADE ON DELETE RESTRICT,
 dni_empleado VARCHAR(9) NOT NULL REFERENCES empleado(dni) ON UPDATE CASCADE ON DELETE RESTRICT,
 fecha DATE NOT NULL,
 importe_total NUMERIC(12,2) NOT NULL CHECK(importe_total >= 0)
);
